import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { EdgeTTS, Constants } from "@andresaya/edge-tts";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const curriculumPaths = [
  path.join(root, "lib", "lesson-data.ts"),
  path.join(root, "components", "translate-crisis-game.tsx")
];
const outputDirectory = path.join(root, "public", "audio", "pt-pt");
const manifestPath = path.join(root, "lib", "portuguese-audio-manifest.ts");
const voices = {
  feminine: "pt-PT-RaquelNeural",
  masculine: "pt-PT-DuarteNeural"
};

const curriculumSources = await Promise.all(curriculumPaths.map((filePath) => readFile(filePath, "utf8")));
const phrases = curriculumSources.flatMap((source) =>
  [...source.matchAll(/portuguese:\s*"((?:\\.|[^"\\])*)"/g)]
    .map((match) => JSON.parse(`"${match[1]}"`))
);
const interfacePhrases = ["O meu progresso", "Continue a aprender português"];
const individualWords = phrases.flatMap((phrase) =>
  phrase
    .replace(/[.,!?;:()[\]“”"]/g, " ")
    .split(/[\s/]+/)
    .map((word) => word.trim())
    .filter(Boolean)
);
const uniquePhrases = [...new Set([...phrases, ...individualWords, ...interfacePhrases])];

await mkdir(outputDirectory, { recursive: true });

function audioFilename(text, gender) {
  const hash = createHash("sha256").update(`${gender}:${text}`).digest("hex").slice(0, 16);
  return `${gender}-${hash}.mp3`;
}

async function generateOne(text, gender) {
  const filename = audioFilename(text, gender);
  const outputPath = path.join(outputDirectory, filename);
  if (!existsSync(outputPath)) {
    const tts = new EdgeTTS();
    await tts.synthesize(text, voices[gender], {
      rate: "-8%",
      outputFormat: Constants.OUTPUT_FORMAT.AUDIO_24KHZ_48KBITRATE_MONO_MP3
    });
    await tts.toFile(outputPath.replace(/\.mp3$/, ""));
  }
  return `/audio/pt-pt/${filename}`;
}

const manifest = {};
let nextIndex = 0;
let completed = 0;
async function generateWorker() {
  while (nextIndex < uniquePhrases.length) {
    const index = nextIndex;
    nextIndex += 1;
    const text = uniquePhrases[index];
    const [feminine, masculine] = await Promise.all([
      generateOne(text, "feminine"),
      generateOne(text, "masculine")
    ]);
    manifest[text] = { feminine, masculine };
    completed += 1;
    process.stdout.write(`\rGenerated ${completed}/${uniquePhrases.length} phrases`);
  }
}

await Promise.all(Array.from({ length: 4 }, () => generateWorker()));

const source = `// Generated by scripts/generate-portuguese-audio.mjs.\n` +
  `export const portugueseAudioManifest: Record<string, { feminine: string; masculine: string }> = ${JSON.stringify(manifest, null, 2)};\n`;
await writeFile(manifestPath, source, "utf8");
process.stdout.write(`\nAudio manifest written to ${manifestPath}\n`);
